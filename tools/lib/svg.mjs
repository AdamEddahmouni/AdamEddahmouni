/**
 * Shared SVG primitives for the profile design system.
 *
 * Everything rendered into assets/ goes through here so that the grid, type
 * scale, radii, motion vocabulary and palette are applied identically across
 * every asset. Nothing in this file reaches the network at render time - font
 * subsets and icon paths are resolved beforehand by tools/fetch-fonts.mjs and
 * tools/fetch-icons.mjs and read from tools/lib/embedded.json.
 */

import { readFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
export const ROOT = join(here, '..', '..')

export const tokens = JSON.parse(
  readFileSync(join(ROOT, 'tools', 'design-tokens.json'), 'utf8'),
)

/** Simple Icons paths, generated by tools/fetch-icons.mjs and committed. */
export const icons = existsSync(join(here, 'icons.json'))
  ? JSON.parse(readFileSync(join(here, 'icons.json'), 'utf8'))
  : {}

// ---------------------------------------------------------------------------
// text helpers
