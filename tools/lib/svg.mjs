/** Rounded surface used by every card in the system. */
export function panel(x, y, w, h, s, { radius = tokens.radius.card, fill, stroke, shadow = true, delay = '' } = {}) {
  const sc = schemeOf(s)
  return `<g${delay ? ` class="rise ${delay}"` : ''}>
${shadow ? `<rect x="${x}" y="${y + 3}" width="${w}" height="${h}" rx="${radius}" fill="#000" opacity="${s === 'dark' ? '.34' : '.07'}"/>` : ''}
<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${radius}" fill="${fill ?? sc.surface}" stroke="${stroke ?? sc.border}" stroke-width="1"/>
</g>`
}

/** Pill-shaped chip with a centred label. Returns the markup plus its width. */
export function chip(x, y, label, s, { accent: ac, size = tokens.type.scale.micro, padX = 10, h = 22, stroke } = {}) {
  const sc = schemeOf(s)
  const w = Math.round(label.length * size * 0.62 + padX * 2)
  const color = ac ? accent(s, ac) : sc.textMuted
  return {
    w,
    markup: `<g><rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${tokens.radius.chip}" fill="${color}" fill-opacity="${s === 'dark' ? '.13' : '.1'}" stroke="${stroke ?? color}" stroke-opacity=".32"/>` +
      text(x + w / 2, y + h / 2 + size * 0.36, label, {
        size, family: 'mono', weight: 500, fill: color, anchor: 'middle',
      }) + `</g>`,
  }
}

/** Breathing status dot. */
export function statusDot(cx, cy, s, r = 4) {
  const sc = schemeOf(s)
  const c = sc.brand.teal
  return `<g><circle cx="${cx}" cy="${cy}" r="${r + 5}" fill="${c}" opacity=".18" class="breathe" style="transform-origin:${cx}px ${cy}px"/><circle cx="${cx}" cy="${cy}" r="${r}" fill="${c}"/></g>`
}

/**
 * Ambient dot grid. Emitted as a <pattern> rather than one circle per cell:
 * a 1200x424 field is ~800 elements inline, which is ~32 KB of markup, versus
 * a single rect here.
 */
export function dotField(id, s, step = 26, r = 1) {
  const sc = schemeOf(s)
  return `<pattern id="${id}" width="${step}" height="${step}" patternUnits="userSpaceOnUse"><circle cx="${r}" cy="${r}" r="${r}" fill="${sc.gridDot}"/></pattern>`
}

export const dotFill = (x, y, w, h, id, opacity = 1) =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="url(#${id})" opacity="${opacity}"/>`

/** Grain overlay. Flat gradients band badly on large areas; this dithers them. */
export function grain(s) {
  const sc = schemeOf(s)
  return `<rect width="100%" height="100%" filter="url(#grainF)" opacity="${sc.grain}" style="mix-blend-mode:overlay"/>`
}

// ---------------------------------------------------------------------------
// contrast gate
// ---------------------------------------------------------------------------

const srgb = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)

export function luminance(hex) {
  let h = hex.replace('#', '')
  if (h.length === 3) h = h.split('').map((c) => c + c).join('')
  const [r, g, b] = [0, 2, 4].map((i) => srgb(parseInt(h.slice(i, i + 2), 16) / 255))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}

export const aa = (a, b, large = false) => contrast(a, b) >= (large ? 3 : 4.5)
