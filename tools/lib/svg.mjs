export const esc = (s) =>
  String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')

export const schemeOf = (s) => tokens.schemes[s]

// ---------------------------------------------------------------------------
// typography
// ---------------------------------------------------------------------------

export const display = (size, weight = 700) =>
  `${weight} ${size}px '${tokens.type.display.family}', ${tokens.type.bodyStack}`
export const mono = (size, weight = 500) =>
  `${weight} ${size}px '${tokens.type.mono.family}', ${tokens.type.monoStack}`
export const body = (size, weight = 400) =>
  `${weight} ${size}px ${tokens.type.bodyStack}`

/** A <text> node with the project's typographic defaults applied. */
export function text(x, y, str, opts = {}) {
  const {
    size = tokens.type.scale.body,
    family = 'body',
    weight = 400,
    fill = 'text',
    anchor = 'start',
    tracking = 0,
    tabular = false,
    opacity,
    extra = '',
  } = opts
  const font = family === 'display' ? display(size, weight)
    : family === 'mono' ? mono(size, weight)
    : body(size, weight)
  const attrs = [
    `x="${x}"`, `y="${y}"`,
    `font-family="${esc(font)}"`,
    `font-size="${size}"`,
    `fill="${fill}"`,
  ]
  // text() owns typography. Letting a caller also pass font-family through
  // `extra` produces a duplicate attribute, which makes the whole SVG invalid
  // XML and the asset silently fails to render. Fail loudly instead.
  if (/font-family/.test(extra)) {
    throw new Error('text(): use family/size/weight, not extra font-family (duplicate attribute)')
  }
  if (weight !== 400) attrs.push(`font-weight="${weight}"`)
  if (anchor !== 'start') attrs.push(`text-anchor="${anchor}"`)
  if (tracking) attrs.push(`letter-spacing="${tracking}"`)
  if (opacity !== undefined) attrs.push(`opacity="${opacity}"`)
  if (tabular) attrs.push('style="font-variant-numeric:tabular-nums"')
  if (extra) attrs.push(extra)
  return `<text ${attrs.join(' ')}>${esc(str)}</text>`
}

