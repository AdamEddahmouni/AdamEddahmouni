export const accent = (s, name) => schemeOf(s).brand[name]

/**
 * Greedy word wrap for SVG text, which has no automatic wrapping.
 *
 * Character width is approximated per family rather than measured, because
 * measurement needs a layout engine. The ratios are tuned so the estimate errs
 * slightly wide, which is the safe direction: a line that looks short rather
 * than one that silently overruns the card.
 */
export function wrapText(str, maxWidth, { size = 12, ratio = 0.53, maxLines = 99 } = {}) {
  const perLine = Math.max(8, Math.floor(maxWidth / (size * ratio)))
  const words = String(str).split(/\s+/)
  const lines = []
  let line = ''
  for (const word of words) {
    const candidate = line ? `${line} ${word}` : word
    if (candidate.length > perLine && line) {
      lines.push(line)
      line = word
    } else {
      line = candidate
    }
  }
  if (line) lines.push(line)
  if (lines.length > maxLines) {
    const kept = lines.slice(0, maxLines)
    kept[maxLines - 1] = kept[maxLines - 1].replace(/.{0,3}$/, '') + '…'
    return kept
  }
  return lines
}

